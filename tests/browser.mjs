import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const base=process.env.NETSCOPE_URL||'http://127.0.0.1:8765';
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];
const context=await browser.newContext({viewport:{width:1440,height:1050},reducedMotion:'reduce'});
const page=await context.newPage();
page.on('pageerror',error=>errors.push(error.message));
try {
  await page.goto(base);
  await page.locator('#topology canvas').waitFor();
  await page.waitForFunction(()=>document.querySelectorAll('.peer-row').length>0);
  assert.notEqual(await page.locator('#rx-rate').innerText(),'—');
  assert.ok(await page.locator('.node-label').count()>1);
  const peer=await page.locator('.peer-row').nth(1).getAttribute('data-peer');
  await page.locator('.peer-row').nth(1).click();
  assert.equal(await page.locator('.selected-ip').innerText(),peer);
  await page.locator('#search').fill('no-such-peer-1234567');
  await page.locator('#graph-empty').waitFor({state:'visible'});
  assert.equal(await page.locator('.peer-row').count(),0);
  await page.locator('#search').fill('');
  await page.locator('[data-protocol="UDP"]').click();
  const protocols=await page.locator('tbody .protocol-badge').allTextContents();
  assert.ok(protocols.every(text=>text==='UDP'));
  await page.locator('[data-protocol="ALL"]').click();
  await page.locator('#pause-btn').click();
  assert.equal(await page.locator('#live-status').innerText(),'PAUSED');
  await page.waitForTimeout(1300);
  assert.equal(await page.locator('#live-status').innerText(),'PAUSED');
  await page.locator('#pause-btn').click();
  await page.locator('[data-tab="packets"]').click();
  const captureSnapshot=await (await page.request.get(base+'/api/snapshot')).json();
  if(!captureSnapshot.capture.packets)assert.ok((await page.locator('#table-content').innerText()).includes('尚未开启'));
  else assert.ok(await page.locator('[data-packet]').count()>0);
  await page.locator('[data-tab="processes"]').click();
  assert.ok(await page.locator('tbody tr').count()>0);
  await page.locator('[data-tab="connections"]').click();
  await page.locator('#about-btn').click();
  assert.ok(await page.locator('#detail-dialog').isVisible());
  assert.ok((await page.locator('#dialog-content').innerText()).includes('256'));
  await page.locator('#dialog-close').click();
  await page.locator('#fullscreen-btn').click();
  assert.ok(await page.locator('.observatory.expanded').isVisible());
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.observatory.expanded').count(),0);
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:'test-results/desktop.png',fullPage:true});
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:2,reducedMotion:'reduce'});
  mobile.on('pageerror',error=>errors.push(error.message));
  await mobile.goto(base);
  await mobile.locator('#topology canvas').waitFor();
  await mobile.waitForFunction(()=>document.querySelectorAll('.peer-row').length>0);
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile page should not overflow horizontally');
  await mobile.locator('.peer-row').first().click();
  assert.ok(await mobile.locator('.selected-ip').isVisible());
  await mobile.evaluate(()=>scrollTo(0,0));
  await mobile.screenshot({path:'test-results/mobile.png',fullPage:true});
  await mobile.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: real metrics, Three.js, peer selection, search, protocols, pause/resume, tabs, dialog, fullscreen, desktop and mobile.');
} finally {await context.close();await browser.close();}
